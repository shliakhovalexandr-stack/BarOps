/* ============================================================
   BarOps — shared/stores.js
   Впізнавання складу юрособи ТОВ за назвою.

   Дзеркало MAIN_STORE_RE з бекендного src/lib/store-split.js. Тримайте їх
   однаковими: фронт цією ж перевіркою будує порядок складів для розкладки, і
   розбіжність означала б, що фронт і бекенд по-різному розуміють, де ТОВ.

   ⚠ Ніяких \b: у JS межа слова визначена лише для [A-Za-z0-9_], тож
   /\bтов\b/i.test('Бар ТОВ') === false — кирилиця для \b «не буква».
   Через це попередня перевірка не спрацьовувала ЖОДНОГО разу, і замість
   розкладки все йшло одним документом на один склад.
   ============================================================ */

export const MAIN_STORE_RE = /(^|[^a-zа-яіїєґ0-9])т(з)?ов([^a-zа-яіїєґ0-9]|$)/i;

export function isMainStoreName(name) {
  return MAIN_STORE_RE.test(String(name || ''));
}
